"""The 'No, that wasn't me' link in the ask by email: https://<pwa>/no/<request id>?exp=<epoch>&sig=<hmac>.

The signature (HMAC-SHA256 over the request id and the expiry, key in Secrets Manager) is the only credential: no login,
no token, and only a No. A GET shows the button; only the POST records (mail scanners prefetch links). A Yes stays out
because the mailbox is the channel scammers hijack (verdict.record_answer refuses it anyway).
"""

import hmac
import os
import re
from dataclasses import dataclass
from hashlib import sha256

import boto3

from shared.enums import AskLinkOutcome

LINK_PATH_PREFIX = "/no/"
LINK_LIFETIME_SECONDS = 24 * 60 * 60  # a late No still counts, so the link outlives the 10-minute hold
SIGNATURE_PREFIX_LENGTH = 16  # enough of the signature to dedupe one link's clicks on inboundMessageIds
REQUEST_ID_PATTERN = re.compile(r"^req-[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$")
SIGNATURE_PATTERN = re.compile(r"^[0-9a-f]{64}$")

_signing_key: bytes | None = None


@dataclass(frozen=True)
class LinkCheck:
    """One link after verification; request_id and signature are set only when VALID."""

    outcome: AskLinkOutcome
    request_id: str = ""
    signature: str = ""


def get_signing_key() -> bytes:
    """The key lives in Secrets Manager (generated by the CDK stack); fetched once per container, never logged."""
    global _signing_key
    if _signing_key is None:
        secret = boto3.client("secretsmanager").get_secret_value(SecretId=os.environ["ASK_LINK_SECRET_NAME"])
        _signing_key = secret["SecretString"].strip().encode()
    return _signing_key


def sign(request_id: str, expires_epoch: int) -> str:
    return hmac.new(get_signing_key(), f"no:{request_id}:{expires_epoch}".encode(), sha256).hexdigest()


def build_no_link(base_url: str, request_id: str, now_epoch: int) -> str:
    expires_epoch = now_epoch + LINK_LIFETIME_SECONDS
    return f"{base_url}{LINK_PATH_PREFIX}{request_id}?exp={expires_epoch}&sig={sign(request_id, expires_epoch)}"


def verify_no_link(raw_path: str, query: dict | None, now_epoch: int) -> LinkCheck:
    """Shape first (nothing is signed over a malformed input), then expiry, then the constant-time signature compare."""
    query = query or {}
    request_id = raw_path.removeprefix(LINK_PATH_PREFIX) if raw_path.startswith(LINK_PATH_PREFIX) else ""
    expires_text, signature = str(query.get("exp", "")), str(query.get("sig", ""))
    if not (REQUEST_ID_PATTERN.match(request_id) and expires_text.isdigit() and SIGNATURE_PATTERN.match(signature)):
        return LinkCheck(AskLinkOutcome.MALFORMED)
    if int(expires_text) < now_epoch:
        return LinkCheck(AskLinkOutcome.EXPIRED)
    if not hmac.compare_digest(sign(request_id, int(expires_text)), signature):
        return LinkCheck(AskLinkOutcome.BAD_SIGNATURE)
    return LinkCheck(AskLinkOutcome.VALID, request_id, signature)
